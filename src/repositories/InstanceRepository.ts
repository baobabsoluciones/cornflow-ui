import client from '@cornflow-ui/core/api/Api'
import { useGeneralStore } from '@cornflow-ui/core/stores/general'
import { InstanceCore } from '@cornflow-ui/core/models/Instance'
import {
  getApiErrorMessageFromContent,
  getMessageFromResponseContent,
} from '@cornflow-ui/core/utils/i18nUtils'
import {
  stripFrontendRowIdsFromInstanceData,
  stripInvisibleParameterPropertiesFromInstanceData,
} from '@cornflow-ui/core/utils/schemaUtils'
import type { ExecutionEndpoint } from '@cornflow-ui/core/utils/executionEndpoints'
import {
  parseExecutionDataFilter,
  type ExecutionDataFilterAnswer,
} from '@cornflow-ui/core/utils/executionDataFilter'

export default class InstanceRepository {
  /**
   * Get an instance by id, from Cornflow's `GET /instance/<id>/data/` unless `endpoint` points
   * elsewhere: the instance of a loaded execution is read where the frontend config says (see
   * `resolveExecutionEndpoint`).
   */
  async getInstance(
    id: string,
    endpoint: ExecutionEndpoint = {
      path: `/instance/${id}/data/`,
      isExternal: false,
    },
  ): Promise<InstanceCore> {
    const { instance } = await this.getInstanceData(id, endpoint)
    return instance
  }

  /**
   * The instance, as `getInstance` reads it, and the `data_filter` of the answer when the backend
   * gives the instance in parts (see `utils/executionDataFilter.ts`). `query` goes with the
   * request: the value to read the instance for.
   */
  async getInstanceData(
    id: string,
    endpoint: ExecutionEndpoint = {
      path: `/instance/${id}/data/`,
      isExternal: false,
    },
    query: Record<string, string> = {},
  ): Promise<{ instance: InstanceCore; dataFilter: ExecutionDataFilterAnswer | null }> {
    const response = await client.get(endpoint.path, query, {}, endpoint.isExternal)

    if (response.status === 200) {
      const { Instance } = useGeneralStore().appConfig
      const instanceContent = response.content
      const instance = new Instance(
        instanceContent.id,
        instanceContent.data,
        useGeneralStore().schemaConfig.instanceSchema,
        useGeneralStore().schemaConfig.instanceChecksSchema,
        useGeneralStore().getSchemaName,
        instanceContent.checks,
      )
      return {
        instance,
        dataFilter: parseExecutionDataFilter(instanceContent.data_filter),
      }
    } else {
      throw new Error('Error getting instance')
    }
  }

  /**
   * Launches the data checks for an instance. `schema` is the DAG of the instance: a
   * deployment closed to the DAGs of each user rejects the request without it. The
   * execution `config` travels with the request so the checks run under the same
   * parameters as the solve will, including the load filters with `in_config` (the ETL
   * filtered the data with them).
   */
  async launchInstanceDataChecks(
    id: string,
    schema: string,
    config?: Record<string, any>,
  ) {
    const body =
      config && Object.keys(config).length > 0 ? { schema, config } : { schema }
    const response = await client.post(
      `/data-check/instance/${id}/`,
      body,
      {
        'Content-Type': 'application/json',
      },
    )

    if (response.status === 201) {
      return response.content
    } else {
      const msg = getMessageFromResponseContent(
        response?.content,
        `Error launching instance data checks: Status ${response.status}`,
      )
      throw new Error(msg)
    }
  }

  async createInstance(data) {
    const store = useGeneralStore()
    const instanceSchema = store.schemaConfig?.instanceSchema
    const visibleData = instanceSchema
      ? stripInvisibleParameterPropertiesFromInstanceData(
          data.instance.data,
          instanceSchema,
        )
      : data.instance.data
    // Row ids generated by the UI (edit tracking) must never reach the backend.
    const cleanedData = stripFrontendRowIdsFromInstanceData(
      visibleData,
      instanceSchema,
    )
    const json = {
      data: cleanedData,
      name: data.name,
      schema: store.getSchemaName,
    }
    const response = await client.post('/instance/', json, {
      'Content-Type': 'application/json',
    })

    if (response.status === 201) {
      return response.content
    } else {
      throw new Error(
        getApiErrorMessageFromContent(response.content, 'Error creating instance'),
      )
    }
  }

  /**
   * Deletes an instance (`DELETE /instance/<id>/`). True when Cornflow deleted it.
   * Cornflow also deletes the executions of that instance, so only delete instances the UI created for itself
   * (e.g. a temporary copy of a draft) and that nothing was launched from.
   */
  async deleteInstance(id: string) {
    const response = await client.remove(`/instance/${id}/`, {})
    return response.status === 200
  }
}
